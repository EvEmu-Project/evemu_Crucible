-- Avoid changing fitting limits for types with an assembled ship carrying fitted items.
UPDATE dgmTypeAttributes AS a
JOIN crucible_hull_dogma AS v ON v.typeID = a.typeID AND v.attributeID = a.attributeID
SET a.valueInt = NULL, a.valueFloat = v.newValue
WHERE ABS(COALESCE(a.valueInt, a.valueFloat) - v.oldValue) <= GREATEST(0.000001, ABS(v.oldValue) * 0.0000002)
  AND (v.fittingChange = 0 OR NOT EXISTS (
      SELECT 1 FROM entity AS hull
      JOIN entity AS fitted ON fitted.locationID = hull.itemID
      WHERE hull.typeID = a.typeID
        AND (fitted.flag BETWEEN 11 AND 34 OR fitted.flag BETWEEN 92 AND 99)));

