UPDATE invTypes AS t JOIN crucible_type_values AS v ON v.typeID = t.typeID AND v.field = 'radius'
SET t.radius = v.newValue WHERE ABS(t.radius - v.oldValue) <= GREATEST(0.000001, ABS(v.oldValue) * 0.0000002);

UPDATE invTypes AS t JOIN crucible_type_values AS v ON v.typeID = t.typeID AND v.field = 'mass'
